def review_payload(data: dict[str, Any]) -> dict[str, Any]:
    """What the review page's JavaScript gets: the sample, its texts, the labels and the committed review."""
    return {k: v for k, v in data.items() if k != "items"} | {
        "items": [{k: i[k] for k in ("id", "kind", "role", "language", "title", "checks", "text")} for i in data["items"]],
        "labels": CHECKS, "guidance": [list(g) for g in CHECK_GUIDANCE], "verdict_label": VERDICT_LABEL,
    }


def build_site(config: str | Path, out: str | Path) -> list[str]:
    """Write the project site for `config` into `out`; returns the pages written (site-relative paths)."""
    return Site(config, out).build()
