class Site:
    def __init__(self, config: str | Path, out: str | Path):
        self.config_path = Path(config)
        self.design = load_design(config)
        self.cfg = load_site_config(config)
        self.root = self.cfg.root
        self.out = Path(out)
        self.corpus = load_corpus_index(self.design)
        self.results = self.root / self.cfg.results
        self.pages: list[str] = []
        self._review: tuple[dict[str, Any] | None] | None = None  # review_data, built once

    # paths and links

    def link(self, frm: str, to: str) -> str:
        """The relative link from page `frm` to site path `to` (both relative to the site root)."""
        anchor = ""
        if "#" in to:
            to, anchor = to.split("#", 1)
            anchor = "#" + anchor
        if not to:
            return anchor
        return posixpath.relpath(to, posixpath.dirname(frm) or ".") + anchor

    def write(self, path: str, title: str, body: str, *, title_key: str = "", scripts: tuple[str, ...] = (),
              crumbs: tuple[tuple[str, str], ...] = ()) -> None:
        """Write one page. `crumbs` are the pages above it, as (site path, label HTML), shown over the title."""
        nav = "".join(
            f'<li><a href="{esc(self.link(path, href))}"'
            + (' aria-current="page"' if href == path or (href != "index.html" and path.startswith(href.split("/")[0] + "/")) else "")
            + f">{ui(key)}</a></li>"
            for href, key in NAV
        )
        h1 = ui(title_key, "h1") if title_key else f"<h1>{esc(title)}</h1>"
        # deferred: the scripts load beside the page and run once it is parsed, so they never block its first paint
        script_tags = "".join(f'<script defer src="{esc(self.link(path, s))}"></script>\n'
                              for s in ("assets/site.js", *scripts))
        trail = ""
        if crumbs:
            trail = (f'<nav class="crumbs"{aria("crumbs.label")}><ol>'
                     + "".join(f'<li><a href="{esc(self.link(path, to))}">{label}</a></li>' for to, label in crumbs)
                     + "</ol></nav>\n")
        page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>{esc(title)} · HCAI</title>
<script>{HEAD_SCRIPT}</script>
<link rel="stylesheet" href="{esc(self.link(path, 'assets/style.css'))}">
{script_tags}</head>
<body>
<a class="skip" href="#main">{ui("skip")}</a>
<header class="site-header">
<div class="bar">
<a class="brand" href="{esc(self.link(path, 'index.html'))}">HCAI</a>
<nav class="site-nav"{aria("nav.label")}><ul>{nav}</ul></nav>
<div class="prefs js-only">
<button type="button" id="theme-toggle" class="pref" data-i18n="theme.auto">{esc(UI['theme.auto'][0])}</button>
<button type="button" id="lang-toggle" class="pref" aria-label="{esc(UI['lang.switch.label'][0])}" lang="pt">PT</button>
</div>
</div>
</header>
<main id="main" tabindex="-1">
{trail}{h1}
{body}
</main>
<footer class="site-footer">{ui("footer", "p")}</footer>
</body>
</html>
"""
        target = self.out / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(page, encoding="utf-8")
        self.pages.append(path)

    def pager(self, frm: str, prev: tuple[str, str] | None, nxt: tuple[str, str] | None) -> str:
        """Links from page `frm` to the previous and the next page of its series, each (site path, label HTML)."""
        links = "".join(
            f'<a class="pager-{rel}" rel="{rel}" href="{esc(self.link(frm, near[0]))}">{ui(key)}: {near[1]}</a>'
            for rel, key, near in (("prev", "pager.prev", prev), ("next", "pager.next", nxt)) if near)
        return f'<nav class="pager"{aria("pager.label")}>{links}</nav>' if links else ""

    def copy(self, source: Path, path: str) -> str:
        target = self.out / path
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        return path

    # build

    def build(self) -> list[str]:
        self._prepare_out()
        self._assets()
        self.home()
        self.corpus_pages()
        self.review_page()
        self.pilot_page()
        self.results_page()
        self.decision_pages()
        self.configs_page()
        return self.pages

    def _prepare_out(self) -> None:
        if self.out.exists():
            if not (self.out / MARKER).exists() and any(self.out.iterdir()):
                raise FileExistsError(f"{self.out} exists and was not written by hcai site; choose another --out")
            shutil.rmtree(self.out)
        self.out.mkdir(parents=True)
        (self.out / MARKER).write_text("written by hcai site; this directory is replaced on every build\n")
        (self.out / ".nojekyll").write_text("")

    def _assets(self) -> None:
        (self.out / "assets").mkdir(parents=True, exist_ok=True)
        (self.out / "assets" / "style.css").write_text(themed_css((ASSETS / "style.css").read_text()), encoding="utf-8")
        self.copy(ASSETS / "review.js", "assets/review.js")
        self.copy(ASSETS / "variants.js", "assets/variants.js")
        strings = {"en": {k: v[0] for k, v in UI.items()}, "pt": {k: v[1] for k, v in UI.items()}}
        script = (ASSETS / "site.js").read_text().replace("/*STRINGS*/null", json.dumps(strings, ensure_ascii=False))
        (self.out / "assets" / "site.js").write_text(script, encoding="utf-8")

    # home

    def _proposal(self) -> tuple[str, list[tuple[str, str]]]:
        tex = self.root / "proposal" / "ijcai27.tex"
        if not tex.exists():
            return "", []
        source = tex.read_text()
        abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", source, re.S)
        rqs = re.findall(r"\\item\[\\textbf\{(RQ\d)\}\]\s*(.*)", source)
        return (latex_to_text(abstract.group(1)) if abstract else "",
                [(rq, latex_to_text(text)) for rq, text in rqs])

    def home(self) -> None:
        path = "index.html"
        abstract, rqs = self._proposal()
        # a hub: what the project is in one paragraph, then every part with where it stands, then the prose
