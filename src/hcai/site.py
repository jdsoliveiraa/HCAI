    def base_cv_page(self, cv: CorpusCV) -> None:
        path = f"corpus/{cv.id}.html"
        d = self.design
        series = self.corpus.base_cvs if self.corpus else [cv]
        k = series.index(cv)
        prev, nxt = (series[k - 1] if k else None), (series[k + 1] if k + 1 < len(series) else None)
        pager = self.pager(path, *((f"corpus/{o.id}.html", esc(o.id)) if o else None for o in (prev, nxt)))
        contents = toc([("h-ids", ui("corpus.identities")), ("h-tpl", ui("corpus.template")),
                        ("h-var", ui("corpus.variants"))])
        meta = (f'<dl class="meta"><dt>{ui("corpus.quality")}</dt><dd>{esc(cv.quality)}</dd>'
                f'<dt>{ui("corpus.borderline")}</dt><dd>{self._borderline(cv.borderline)}</dd>'
                + (f'<dt>{ui("corpus.note")}</dt><dd>{esc(cv.borderline_note)}</dd>' if cv.borderline_note else "")
                + "</dl>" + contents)
        # identities table
        rows = [[i.id, i.gender, i.origin, self._identity_name(i, cv.id),
                 " / ".join(self._nationality(i, lang) for lang in cv.templates)] for i in d.identities]
        identities = (f'<section aria-labelledby="h-ids">{ui("corpus.identities", "h2", id="h-ids")}'
                      + table([UI["corpus.identity"][0], UI["corpus.gender"][0], UI["corpus.origin"][0],
                               UI["corpus.name"][0], UI["corpus.nationality"][0]], rows) + "</section>")
        templates = "".join(
            f'<section class="doc" lang="{esc(lang)}" aria-label="{esc(LANGUAGE_NAMES.get(lang, lang))}">'
            f'<p class="doc-lang">{esc(lang.upper())}</p>{render_markdown(self._template_view(text), trusted=False, shift=2)}</section>'
            for lang, text in cv.templates.items())
        template = (f'<section aria-labelledby="h-tpl">{ui("corpus.template", "h2", id="h-tpl")}'
                    f'<p class="muted">{ui("corpus.template.help")}</p><div class="columns slots-on">{templates}</div></section>')
        self.write(path, f"Base CV {cv.id}", meta + identities + template + self._variant_viewer(cv) + pager,
                   scripts=("assets/variants.js",),
                   crumbs=(("corpus/index.html", ui("nav.corpus")), (f"corpus/{cv.role}.html", esc(cv.role))))

    def _nationality(self, identity: Identity, language: str) -> str:
        try:
            return identity.nationality_in(language)
        except ValueError:
            return "?"

    @staticmethod
    def _template_view(template: str) -> str:
        """The template with its slots shown as highlighted placeholders."""
        text = re.sub(r"\{\{([^{}|]*)\|([^{}|]*)\}\}",
                      lambda m: m.group(1) if m.group(1) == m.group(2) else f"{OPEN}[{m.group(1)} / {m.group(2)}]{CLOSE}",
                      template)
        text = text.replace("$work_eligibility", f"{OPEN}[right to work + Portuguese proficiency lines]{CLOSE}")
        text = text.replace("$nationality", f"{OPEN}[nationality]{CLOSE}").replace("$name", f"{OPEN}[name]{CLOSE}")
        return text.replace("$$", "$")

    def _variant_viewer(self, cv: CorpusCV) -> str:
        d = self.design
        sections, problems = [], []
        for lang, template in cv.templates.items():
            for identity in d.identities:
                try:
                    text = render_variant(template, name=self._identity_name(identity, cv.id),
                                          nationality=identity.nationality_in(lang), gender=identity.gender,
                                          language=lang, mark=(OPEN, CLOSE))
                except (TemplateError, ValueError, KeyError) as e:
                    problems.append(f"{lang} / {identity.id}: {e}")
                    continue
                sections.append(
                    f'<section class="variant doc" id="v-{esc(identity.id)}-{esc(lang)}" data-lang="{esc(lang)}" '
                    f'data-identity="{esc(identity.id)}" lang="{esc(lang)}" aria-label="{esc(identity.id)}, {esc(lang)}">'
                    f'<p class="doc-lang">{esc(identity.id)} · {esc(lang.upper())}</p>'
                    f"{render_markdown(text, trusted=False, shift=2)}</section>")
        if not sections:
            body = "".join(f"<p>{esc(p)}</p>" for p in problems) or not_generated()
            return f'<section aria-labelledby="h-var">{ui("corpus.variants", "h2", id="h-var")}{body}</section>'
        langs = "".join(
            f'<label><input type="radio" name="v-lang" value="{esc(lang)}"{" checked" if k == 0 else ""}> {esc(lang.upper())}</label>'
            for k, lang in enumerate(cv.templates))
        ids = "".join(
            f'<label><input type="radio" name="v-identity" value="{esc(i.id)}"{" checked" if k == 0 else ""}> '
            f'{esc(i.id)} <span class="muted">({esc(self._identity_name(i, cv.id))})</span></label>'
            for k, i in enumerate(d.identities))
        others = "".join(f'<option value="{esc(i.id)}">{esc(i.id)} ({esc(self._identity_name(i, cv.id))})</option>'
                         for i in d.identities)
        compare = (f'<p class="variant-compare"><label for="v-compare">{ui("corpus.compare")}</label> '
                   f'<select id="v-compare"><option value="" data-i18n="corpus.compare.none">'
                   f'{esc(UI["corpus.compare.none"][0])}</option>{others}</select> '
                   f'{ui("corpus.compare.help", class_="muted")}</p>')
        controls = (f'<div class="variant-controls" hidden><fieldset><legend>{ui("corpus.language")}</legend>{langs}</fieldset>'
                    f'<fieldset><legend>{ui("corpus.identity")}</legend>{ids}</fieldset>{compare}</div>')
        errors = "".join(f'<p class="error">{esc(p)}</p>' for p in problems)
        return (f'<section aria-labelledby="h-var">{ui("corpus.variants", "h2", id="h-var")}'
                f'<p class="muted">{ui("corpus.variants.choose", class_="js-only")} '
                f'{ui("corpus.variants.all", class_="no-js-only")} {ui("corpus.variants.help")}</p>{controls}{errors}'
                f'<div class="variants slots-on">{"".join(sections)}</div></section>')

    # review

    def review_data(self) -> dict[str, Any] | None:
        """The review sample with each item's text (Markdown source and HTML), and the committed review if any."""
        if self._review is None:
            self._review = (self._build_review_data(),)
        return self._review[0]

    def _build_review_data(self) -> dict[str, Any] | None:
        c = self.corpus
        if c is None:
            return None
        d = self.design
        seed = d.seed if d.seed is not None else 42
        sample = review_sample(
            d.roles, d.quality_levels, c.languages, list(c.job_ads),
            [SampleCV(cv.id, cv.role, cv.quality, bool(cv.borderline)) for cv in c.base_cvs
             if all(lang in cv.templates for lang in c.languages)],
            [SampleIdentity(i.id, i.gender, i.origin) for i in d.identities], seed,
        )
        identities = {i.id: i for i in d.identities}
        templates = {cv.id: cv.templates for cv in c.base_cvs}
        items: list[dict[str, Any]] = []
        problems: list[str] = []
        for item in sample.items:
            if item.kind == "job_ad":
                text = c.job_ads[item.role].get(item.language)
                if text is None:
                    continue
                marked = text
            else:
                identity = identities[item.identity]
                item = replace(item, name=pick_name(identity, item.base_cv))
                template = templates[item.base_cv][item.language]
                try:
                    text, marked = (render_variant(template, name=item.name, gender=identity.gender,
                                                   nationality=identity.nationality_in(item.language),
                                                   language=item.language, mark=mark)
                                    for mark in (None, (OPEN, CLOSE)))
                except (TemplateError, ValueError) as e:  # shown on the page; the item is left out of the sample
                    problems.append(f"{item.id}: {e}")
                    continue
            items.append(self._review_item(item, text, marked))
        meta = {"corpus_version": c.version, "generator": c.generator, "seed": seed, "languages": c.languages}
        committed, mismatch = None, ""
        record = self.root / f"{self.cfg.review}.json"
        if record.exists():
            try:
                parsed = json.loads(record.read_text())
                mismatch = check_review(parsed, meta, items) or ""
                committed = None if mismatch else parsed
            except (json.JSONDecodeError, UnicodeDecodeError):
                mismatch = "the file is not valid JSON"
        return {"meta": meta, "items": items, "blank": blank_review(meta, items), "committed": committed,
                "committed_mismatch": mismatch, "record": self.cfg.review, "problems": problems}

    @staticmethod
    def _review_item(item: ReviewItem, text: str, marked: str) -> dict[str, Any]:
        return {"id": item.id, "kind": item.kind, "role": item.role, "language": item.language, "title": item.title(),
                "checks": list(item.checks), "text": text, "html": render_markdown(marked, trusted=False, shift=2),
                "quality": item.quality, "borderline": item.borderline, "base_cv": item.base_cv}

