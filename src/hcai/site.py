    @staticmethod
    def _template_view(template: str) -> str:
        """The template with its slots shown as highlighted placeholders."""
        text = re.sub(r"\{\{([^{}|]*)\|([^{}|]*)\}\}",
                      lambda m: m.group(1) if m.group(1) == m.group(2) else f"{OPEN}[{m.group(1)} / {m.group(2)}]{CLOSE}",
                      template)
        text = text.replace("$work_eligibility", f"{OPEN}[right to work + Portuguese proficiency lines]{CLOSE}")
        text = text.replace("$nationality", f"{OPEN}[nationality]{CLOSE}").replace("$name", f"{OPEN}[name]{CLOSE}")
        return text.replace("$$", "$")

    def _variant_viewer(self, cv: CorpusCV) -> str:
        d = self.design
        sections, problems = [], []
        for lang, template in cv.templates.items():
            for identity in d.identities:
                try:
                    text = render_variant(template, name=self._identity_name(identity, cv.id),
                                          nationality=identity.nationality_in(lang), gender=identity.gender,
                                          language=lang, mark=(OPEN, CLOSE))
                except (TemplateError, ValueError, KeyError) as e:
                    problems.append(f"{lang} / {identity.id}: {e}")
                    continue
                sections.append(
                    f'<section class="variant doc" id="v-{esc(identity.id)}-{esc(lang)}" data-lang="{esc(lang)}" '
                    f'data-identity="{esc(identity.id)}" lang="{esc(lang)}" aria-label="{esc(identity.id)}, {esc(lang)}">'
                    f'<p class="doc-lang">{esc(identity.id)} · {esc(lang.upper())}</p>'
                    f"{render_markdown(text, trusted=False, shift=2)}</section>")
        if not sections:
            body = "".join(f"<p>{esc(p)}</p>" for p in problems) or not_generated()
            return f'<section aria-labelledby="h-var">{ui("corpus.variants", "h2", id="h-var")}{body}</section>'
        langs = "".join(
            f'<label><input type="radio" name="v-lang" value="{esc(lang)}"{" checked" if k == 0 else ""}> {esc(lang.upper())}</label>'
            for k, lang in enumerate(cv.templates))
        ids = "".join(
            f'<label><input type="radio" name="v-identity" value="{esc(i.id)}"{" checked" if k == 0 else ""}> '
            f'{esc(i.id)} <span class="muted">({esc(self._identity_name(i, cv.id))})</span></label>'
            for k, i in enumerate(d.identities))
        controls = (f'<div class="variant-controls" hidden><fieldset><legend>{ui("corpus.language")}</legend>{langs}</fieldset>'
                    f'<fieldset><legend>{ui("corpus.identity")}</legend>{ids}</fieldset></div>')
        errors = "".join(f'<p class="error">{esc(p)}</p>' for p in problems)
        return (f'<section aria-labelledby="h-var">{ui("corpus.variants", "h2", id="h-var")}'
                f'<p class="muted">{ui("corpus.variants.help")}</p>{controls}{errors}'
                f'<div class="variants slots-on">{"".join(sections)}</div></section>')

