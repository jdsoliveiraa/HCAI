    def _review_article(self, item: dict[str, Any], items: list[dict[str, Any]]) -> str:
        n = items.index(item)
        aid = f"item-{n}"
        tags = f'<span class="tag">{esc(item["language"].upper())}</span>'
        extra = ""
        if item["kind"] == "cv":
            tags += f' <span class="tag">{esc(item["quality"])}</span>'
            if item["borderline"]:
                tags += f' <span class="tag tag-borderline">{ui("corpus.borderline")}</span>'
            ad = next((k for k, i in enumerate(items) if i["kind"] == "job_ad" and i["role"] == item["role"]
                       and i["language"] == item["language"]), None)
            if ad is not None:
                extra = f' · <a href="#item-{ad}">{ui("review.job_ad_link")}</a>'
            extra += (f' · <a href="{esc(self.link("review.html", "corpus/" + item["base_cv"] + ".html"))}">'
                      f'{ui("review.base_cv")}</a>')
        boxes = "".join(
            f'<label><input type="checkbox" data-check="{esc(c)}"> {esc(CHECKS[c] if c != "mandatory" else "Meets mandatory requirements")}</label>'
            for c in item["checks"])
        # The text comes first and the answers after it: beside the text on a wide screen (they stay in view while
        # it scrolls), below it on a narrow one.
        return (f'<article class="item" id="{aid}" data-item="{esc(item["id"])}" aria-labelledby="{aid}-h" tabindex="-1">'
                f'<h2 id="{aid}-h"><span class="item-n">{n + 1}</span> {esc(item["title"])}</h2><p class="tags">{tags}{extra}</p>'
                '<div class="item-body">'
                f'<div class="doc" lang="{esc(item["language"])}">{item["html"]}</div>'
                '<div class="answers">'
                f'<fieldset class="checks"><legend>{ui("review.checklist")}</legend>{boxes}'
                f'{ui("review.all", "button", type="button", class_="secondary small js-only", data_all="")}</fieldset>'
                f'<p><label for="{aid}-notes">{ui("review.notes")}</label><textarea id="{aid}-notes" data-notes rows="3"></textarea></p>'
                '<p class="item-state js-only" data-state></p>'
                "</div></div></article>")

