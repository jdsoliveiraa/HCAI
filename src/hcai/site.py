    def _hub(self, path: str) -> str:
        """The home page's cards: one per part of the project, with where it stands and a link to its page."""
        def card(to: str, key: str, state: str) -> list[Any]:
            return [Raw(f'<a href="{esc(self.link(path, to))}">{ui(key)}</a>'), Raw(state)]

        probes = sorted((self.root / "docs" / "pilot").glob("check-*.json"))
        run = (self.results / "pilot" / "run_summary.json").exists()
        pilot = ((f'{ui("home.card.probes")} {esc(probes[-1].stem.removeprefix("check-"))}' if probes
                  else ui("home.card.no_probes")) + "; " + ui("home.card.run" if run else "home.card.no_run"))
        adrs = sorted((self.root / "docs" / "adr").glob("[0-9]*.md"))
        configs = sorted((self.root / "configs").glob("*.toml"))
        rows = self._status(path)
        rows[2:2] = [card("pilot.html", "nav.pilot", pilot)]  # after the corpus and the review, before the name check
        rows += [card("decisions/index.html", "nav.decisions", f'{ui("home.card.adrs")} {len(adrs)}'),
                 card("configs.html", "nav.configs", esc(", ".join(f.name for f in configs)) or ui("home.card.no_configs"))]
        cards = "".join(f'<li class="card"><h3>{link}</h3><div class="card-state">'
                        f"{state if isinstance(state, Raw) else esc(state)}</div></li>" for link, state in rows)
        return f'<ul class="cards">{cards}</ul>'

    def _status(self, path: str) -> list[list[Any]]:
        """Where the corpus, the review, the name check and the results stand: rows of (link HTML, state)."""
        rows: list[list[Any]] = []
        c = self.corpus
        rows.append([Raw(f'<a href="{esc(self.link(path, "corpus/index.html"))}">{ui("status.corpus")}</a>'),
                     f"{c.version}: {sum(len(a) for a in c.job_ads.values())} job ads, {len(c.base_cvs)} base CVs "
                     f"({', '.join(c.languages)}), generator {c.generator}" if c else Raw(not_generated())])
        data = self.review_data()
        if data and data["committed"]:
            record = data["committed"]
            verdict = record.get("verdict") if isinstance(record.get("verdict"), dict) else {}
            state = (f"committed ({record.get('reviewer') or 'no reviewer'}, {record.get('date') or 'no date'}); "
                     f"realistic enough to freeze: {yes_no(verdict.get('freeze') is True)}")
        elif data and data["committed_mismatch"]:
            state = f"the committed review does not match the current sample: {data['committed_mismatch']}"
        elif (self.root / f"{self.cfg.review}.json").exists():
            state = "committed, but there is no corpus to check it against"
        else:
            state = "not committed yet"
        rows.append([Raw(f'<a href="{esc(self.link(path, "review.html"))}">{ui("status.review")}</a>'), state])
        names = self.results / "names" / "summary.csv"
        if names.exists():
            with names.open(newline="", encoding="utf-8") as f:
                summary = list(csv.DictReader(f))
            failing = sorted({r["name"] for r in summary if r.get("pass", "").lower() not in ("true", "1", "yes")})
            state = f"{len({r['name'] for r in summary})} names, {len(failing)} failing"
        else:
            state = Raw(not_generated())
        rows.append([Raw(f'<a href="{esc(self.link(path, "pilot.html#names"))}">{ui("status.names")}</a>'), state])
        results = self.results / "results.csv"
        rows.append([Raw(f'<a href="{esc(self.link(path, "results.html"))}">{ui("status.results")}</a>'),
                     f"results.csv present" if results.exists() else Raw(not_generated())])
        return rows

    # corpus

    def corpus_pages(self) -> None:
        path = "corpus/index.html"
        c = self.corpus
        if c is None:
            self.write(path, "Corpus", not_generated(f"uv run hcai corpus {self.config_path}"), title_key="corpus.title")
            return
        intro = (f"<p>Corpus <strong>{esc(c.version)}</strong> (<code>{esc(self._rel_root(c.root))}</code>), generator "
                 f"{esc(c.generator)}, languages {esc(', '.join(c.languages))}. Each base CV is rendered for "
                 f"{len(self.design.identities)} identities in every language.</p>")
        sections, jumps = [], []
        for role in self.design.roles:
            cvs = [cv for cv in c.base_cvs if cv.role == role]
            if role not in c.job_ads and not cvs:
                continue
            levels = ", ".join(f"{sum(cv.quality == q for cv in cvs)} {q}" for q in self.design.quality_levels)
            counts = (f"{len(cvs)} base CVs ({levels}), {sum(bool(cv.borderline) for cv in cvs)} borderline"
                      if cvs else "no base CVs")
            jumps.append((f"h-{role}", esc(role)))
            sections.append(f'<section aria-labelledby="h-{esc(role)}"><h2 id="h-{esc(role)}">{esc(role)}</h2>'
                            f'<p><a href="{esc(self.link(path, f"corpus/{role}.html"))}">{ui("corpus.role_page")}</a>'
                            f' <span class="muted">· {esc(counts)}</span></p>'
                            + self._cv_table(path, cvs) + "</section>")
            self.role_page(role, cvs)
            for cv in cvs:
                self.base_cv_page(cv)
        self.write(path, "Corpus", "\n".join([intro, toc(jumps), *sections]), title_key="corpus.title")

