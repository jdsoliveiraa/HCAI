@dataclass(frozen=True)
class SiteConfig:
    root: Path
    notebook: str = "notebooks/analysis.ipynb"
    report: str = "report/report.pdf"
    results: str = "results"
    review: str = "docs/pilot/cv-realism-review"
    proposal: str = "proposal/ijcai27.pdf"
    repo: str = "jdsoliveiraa/HCAI"

    @property
    def github(self) -> str:
        return f"https://github.com/{self.repo}"


def load_site_config(config: str | Path) -> SiteConfig:
    """The `[site]` section of a design config (every key optional)."""
    config = Path(config)
    raw = tomllib.loads(config.read_text()).get("site", {})
    unknown = set(raw) - {"root", "notebook", "report", "results", "review", "proposal", "repo"}
    if unknown:
        raise ValueError(f"{config}: [site] has unknown keys {sorted(unknown)}")
    root = (config.parent / raw.pop("root", "..")).resolve()
    return SiteConfig(root=root, **{k: str(v) for k, v in raw.items()})


# --- corpus ----------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class CorpusCV:
    id: str  # <role>/<quality>/<cv id>
    role: str
    quality: str
    borderline: bool | None  # None: the corpus has no manifest
    borderline_note: str
    templates: dict[str, str]  # language -> slot template


@dataclass(frozen=True)
class CorpusIndex:
    root: Path
    version: str
    generator: str
    languages: list[str]
    job_ads: dict[str, dict[str, str]]  # role -> language -> Markdown
    base_cvs: list[CorpusCV]


def load_corpus_index(design: Design) -> CorpusIndex | None:
    """What the design's corpus directory holds (as `hcai.variants` reads it), or None when there is nothing."""
    root = design.corpus_dir
    if not root.is_dir():
        return None
    manifest: dict[str, Any] = {}
    if (root / "manifest.json").exists():
        manifest = json.loads((root / "manifest.json").read_text())
    entries = {e["id"]: e for e in manifest.get("base_cvs", [])}
    job_ads: dict[str, dict[str, str]] = {}
    base_cvs: list[CorpusCV] = []
    for role in design.roles:
        ads = {lang: (root / role / f"job_ad.{lang}.md").read_text() for lang in design.languages
               if (root / role / f"job_ad.{lang}.md").exists()}
        if ads:
            job_ads[role] = ads
        for quality in design.quality_levels:
            first = design.languages[0]
            files = sorted((root / role / quality).glob(f"*.{first}.md"))[: design.base_cvs_per_role]
            for f in files:
                cv_id = f"{role}/{quality}/{f.name.removesuffix(f'.{first}.md')}"
                templates = {lang: (root / f"{cv_id}.{lang}.md").read_text() for lang in design.languages
                             if (root / f"{cv_id}.{lang}.md").exists()}
                entry = entries.get(cv_id)
                base_cvs.append(CorpusCV(
                    id=cv_id, role=role, quality=quality,
                    borderline=bool(entry["borderline"]) if entry else None,
                    borderline_note=str(entry.get("borderline_note", "")) if entry else "", templates=templates,
                ))
    if not job_ads and not base_cvs:
        return None
    return CorpusIndex(root=root, version=str(manifest.get("version", root.name)),
                       generator=str(manifest.get("generator", {}).get("model", "hand-written")),
                       languages=list(design.languages), job_ads=job_ads, base_cvs=base_cvs)


# --- HTML helpers ----------------------------------------------------------------------------------------------


def esc(value: Any) -> str:
    return html.escape(str(value), quote=True)


def ui(key: str, tag: str = "span", **attrs: str) -> str:
    """An interface string in English, switchable to PT-PT by assets/site.js."""
    extra = "".join(f' {k.rstrip("_").replace("_", "-")}="{esc(v)}"' for k, v in attrs.items())
    return f'<{tag} data-i18n="{key}"{extra}>{esc(UI[key][0])}</{tag}>'


def render_markdown(text: str, *, trusted: bool, shift: int = 0) -> str:
    """Markdown to HTML. Untrusted text (generated documents) has raw HTML escaped first; slot markers become
    `<mark class="slot">`. Headings are demoted by `shift` levels (at most h6), so a document shown under a page's
    h2 keeps the page's heading outline."""
    if not trusted:
        text = text.replace("&", "&amp;").replace("<", "&lt;")
    # generated documents keep their line breaks (a CV header is one line per fact)
    out = md.markdown(text, extensions=["tables", "fenced_code", "sane_lists", *([] if trusted else ["nl2br"])])
    if shift:
        out = re.sub(r"<(/?)h([1-6])\b", lambda m: f"<{m.group(1)}h{min(6, int(m.group(2)) + shift)}", out)
    return out.replace(OPEN, '<mark class="slot">').replace(CLOSE, "</mark>")


def table(header: list[str], rows: list[list[Any]], caption: str = "") -> str:
    cap = f"<caption>{esc(caption)}</caption>" if caption else ""
    head = "".join(f'<th scope="col">{esc(h)}</th>' for h in header)
    body = "".join("<tr>" + "".join(f"<td>{c if isinstance(c, Raw) else esc(c)}</td>" for c in row) + "</tr>"
                   for row in rows)
    return f'<div class="table-wrap" tabindex="0"><table>{cap}<thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>'


class Raw(str):
    """A table cell that is already HTML."""


def csv_table(path: Path, caption: str = "", limit: int = MAX_ROWS) -> str:
    with path.open(newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    if not rows:
        return f"<p>{esc(path.name)}: empty.</p>"
    out = table(rows[0], rows[1: limit + 1], caption)
    if len(rows) - 1 > limit:
        out += f'<p class="muted">{ui("table.truncated")} ({len(rows) - 1} rows)</p>'
    return out


def not_generated(command: str = "") -> str:
    hint = f" <code>{esc(command)}</code>" if command else ""
    return f'<p class="placeholder">{ui("not_generated")}{hint}</p>'


def yes_no(value: Any) -> str:
    return "?" if value is None else ("yes" if value else "no")


def latex_to_text(text: str) -> str:
    """A light LaTeX-to-text pass for the proposal's abstract and research questions."""
    text = re.sub(r"~?\\cite\{[^}]*\}", "", text)
    text = re.sub(r"\\(?:emph|textbf|textit)\{([^}]*)\}", r"\1", text)
    text = text.replace("\\ ", " ").replace("~", " ").replace("--", "–").replace("\\%", "%").replace("\\&", "&")
    text = text.replace("$\\times$", "×").replace("$\\geq$", "≥").replace("$\\pm", "±").replace("${\\sim}", "~")
    text = re.sub(r"\$([^$]*)\$", r"\1", text)
    return re.sub(r"\s+", " ", text).strip()


